CREATE OR ALTER VIEW f_18_00_a_dtpnt AS
SELECT
  r.DT_RFRNC,
  r.RPRTNG_AGNT_ID,
  r.ACCNTNG_CNSLDTN_LVL,
  r.ACCNTNG_STNDRD,
  'INSTRMNT' AS PSTN_SRC,
  r.INSTRMNT_ID AS PSTN_ID,
  r.ACCNTNG_CLSSFCTN,
  t.TYP_FNNCL_ASST_INSTRMNT_ANNX_V,
  g.GRSS_CRRYNG_AMNT,
  r.PRFRMNG_STTS,
  CAST(NULL AS VARCHAR(255)) AS DBT_SCRTY_PRFRMNG_STTS_TYP,
  a.ENTTY_RL_TYP,
  a.MN_DBTR_INDCTR,
  a.MN_LSS_INDCTR,
  a.MN_DPST_TKNG_CRPRTN_INDCTR,
  CAST(NULL AS VARCHAR(255)) AS PRMRY_ISSR_INDCTR,
  p.INSTTTNL_SCTR,
  p.MLTLTRL_DVLPMNT_BNK_INDCTR
FROM instrmnt_rl_eil AS r
JOIN instrmnt_rl_eil_grss_crryng_amnt AS g
  ON g.DT_RFRNC = r.DT_RFRNC
  AND g.RPRTNG_AGNT_ID = r.RPRTNG_AGNT_ID
  AND g.ACCNTNG_CNSLDTN_LVL = r.ACCNTNG_CNSLDTN_LVL
  AND g.ACCNTNG_STNDRD = r.ACCNTNG_STNDRD
  AND g.INSTRMNT_ID = r.INSTRMNT_ID
  AND g.INSTRMNT_RL_TYP = r.INSTRMNT_RL_TYP
JOIN instrmnt_rl_eil_typ_fnncl_asst AS t
  ON t.DT_RFRNC = r.DT_RFRNC
  AND t.RPRTNG_AGNT_ID = r.RPRTNG_AGNT_ID
  AND t.ACCNTNG_CNSLDTN_LVL = r.ACCNTNG_CNSLDTN_LVL
  AND t.ACCNTNG_STNDRD = r.ACCNTNG_STNDRD
  AND t.INSTRMNT_ID = r.INSTRMNT_ID
  AND t.INSTRMNT_RL_TYP = r.INSTRMNT_RL_TYP
JOIN f_18_00_a_scp AS s
  ON s.DT_RFRNC = r.DT_RFRNC
  AND s.RPRTNG_AGNT_ID = r.RPRTNG_AGNT_ID
  AND s.ACCNTNG_CNSLDTN_LVL = r.ACCNTNG_CNSLDTN_LVL
  AND s.ACCNTNG_STNDRD = r.ACCNTNG_STNDRD
LEFT JOIN instrmnt_entty_rl_assgnmnt_eil AS a
  ON a.DT_RFRNC = r.DT_RFRNC
  AND a.RPRTNG_AGNT_ID = r.RPRTNG_AGNT_ID
  AND a.ACCNTNG_CNSLDTN_LVL = r.ACCNTNG_CNSLDTN_LVL
  AND a.ACCNTNG_STNDRD = r.ACCNTNG_STNDRD
  AND a.INSTRMNT_ID = r.INSTRMNT_ID
LEFT JOIN prty_eil AS p
  ON p.DT_RFRNC = a.DT_RFRNC
  AND p.RPRTNG_AGNT_ID = a.RPRTNG_AGNT_ID
  AND p.ACCNTNG_CNSLDTN_LVL = a.ACCNTNG_CNSLDTN_LVL
  AND p.ACCNTNG_STNDRD = a.ACCNTNG_STNDRD
  AND p.PRTY_ID = a.PRTY_ID
UNION ALL
SELECT
  g.DT_RFRNC,
  g.RPRTNG_AGNT_ID,
  g.ACCNTNG_CNSLDTN_LVL,
  g.ACCNTNG_STNDRD,
  'SCRTY_PSTN' AS PSTN_SRC,
  g.SCRTY_ID AS PSTN_ID,
  g.ACCNTNG_CLSSFCTN,
  t.TYP_FNNCL_ASST_INSTRMNT_ANNX_V,
  g.GRSS_CRRYNG_AMNT,
  CAST(NULL AS VARCHAR(255)) AS PRFRMNG_STTS,
  d.DBT_SCRTY_PRFRMNG_STTS_TYP,
  e.ENTTY_RL_TYP,
  CAST(NULL AS VARCHAR(255)) AS MN_DBTR_INDCTR,
  CAST(NULL AS VARCHAR(255)) AS MN_LSS_INDCTR,
  CAST(NULL AS VARCHAR(255)) AS MN_DPST_TKNG_CRPRTN_INDCTR,
  e.PRMRY_ISSR_INDCTR,
  p.INSTTTNL_SCTR,
  p.MLTLTRL_DVLPMNT_BNK_INDCTR
FROM lng_scrty_pstn_eil_grss_crryng_amnt AS g
JOIN lng_scrty_pstn_eil_typ_fnncl_asst AS t
  ON t.DT_RFRNC = g.DT_RFRNC
  AND t.RPRTNG_AGNT_ID = g.RPRTNG_AGNT_ID
  AND t.ACCNTNG_CNSLDTN_LVL = g.ACCNTNG_CNSLDTN_LVL
  AND t.ACCNTNG_STNDRD = g.ACCNTNG_STNDRD
  AND t.SCRTY_ID = g.SCRTY_ID
  AND t.INVSTR_PRTY_ID = g.INVSTR_PRTY_ID
  AND t.INVSTR_ENTTY_RL_TYP = g.INVSTR_ENTTY_RL_TYP
  AND t.SCRTY_PSTN_BLNC_SHT_RCGNSD_TYP = g.SCRTY_PSTN_BLNC_SHT_RCGNSD_TYP
  AND t.LNG_SHRT_BLNC_SHT_RCGNSD_SCRTY_PSTN_TYP = g.LNG_SHRT_BLNC_SHT_RCGNSD_SCRTY_PSTN_TYP
  AND t.PRDNTL_PRTFL_TYP = g.PRDNTL_PRTFL_TYP
  AND t.ACCNTNG_CLSSFCTN = g.ACCNTNG_CLSSFCTN
JOIN scrty_exchng_trdbl_drvtv_eil AS d
  ON d.DT_RFRNC = g.DT_RFRNC
  AND d.RPRTNG_AGNT_ID = g.RPRTNG_AGNT_ID
  AND d.ACCNTNG_CNSLDTN_LVL = g.ACCNTNG_CNSLDTN_LVL
  AND d.ACCNTNG_STNDRD = g.ACCNTNG_STNDRD
  AND d.SCRTY_EXCHNG_TRDBL_DRVTV_ID = g.SCRTY_ID
JOIN f_18_00_a_scp AS s
  ON s.DT_RFRNC = g.DT_RFRNC
  AND s.RPRTNG_AGNT_ID = g.RPRTNG_AGNT_ID
  AND s.ACCNTNG_CNSLDTN_LVL = g.ACCNTNG_CNSLDTN_LVL
  AND s.ACCNTNG_STNDRD = g.ACCNTNG_STNDRD
LEFT JOIN scrty_entty_rl_assgnmnt_eil AS e
  ON e.DT_RFRNC = g.DT_RFRNC
  AND e.RPRTNG_AGNT_ID = g.RPRTNG_AGNT_ID
  AND e.ACCNTNG_CNSLDTN_LVL = g.ACCNTNG_CNSLDTN_LVL
  AND e.ACCNTNG_STNDRD = g.ACCNTNG_STNDRD
  AND e.SCRTY_EXCHNG_TRDBL_DRVTV_ID = g.SCRTY_ID
LEFT JOIN prty_eil AS p
  ON p.DT_RFRNC = e.DT_RFRNC
  AND p.RPRTNG_AGNT_ID = e.RPRTNG_AGNT_ID
  AND p.ACCNTNG_CNSLDTN_LVL = e.ACCNTNG_CNSLDTN_LVL
  AND p.ACCNTNG_STNDRD = e.ACCNTNG_STNDRD
  AND p.PRTY_ID = e.PRTY_ID
GO

